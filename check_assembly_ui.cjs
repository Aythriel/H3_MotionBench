const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs');
const path=require('path');
const assert=require('assert/strict');
(async()=>{
 const base=process.env.H3_ASSEMBLY_TEST_URL||'http://127.0.0.1:8791';
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const evidence=path.join(__dirname,'.artifacts/assembly-review');
 try {
  const initialExportCount=(await (await page.request.get(base+'/api/assembly/exports')).json()).jobs.length;
  const generationFolders=await (await page.request.get(base+'/api/output-folders')).json();
  await page.goto(base+'/assemble.html');
  await page.locator('[data-add="red-ui"]').waitFor();
  await page.locator('[data-add="red-ui"]').click();
  await page.locator('[data-source="blue-ui"]').dragTo(page.locator('#timeline'));
  assert.equal(await page.locator('.timeline-clip').count(),2);
  assert.match(await page.locator('#resolutionInfo').textContent(),/192 × 128/);
  await page.locator('.timeline-clip').first().dragTo(page.locator('.timeline-clip').last());
  assert.match(await page.locator('.timeline-clip').first().textContent(),/blue-ui/);
  await page.locator('.timeline-clip').first().click();
  await page.locator('#trimOut').fill('0.25'); await page.locator('#trimOut').blur();
  assert.match(await page.locator('#totalDuration').textContent(),/0.75 s/);
  await page.locator('.timeline-clip').first().locator('[data-duplicate]').click();
  assert.equal(await page.locator('.timeline-clip').count(),3);
  await page.locator('#undo').click();
  assert.equal(await page.locator('.timeline-clip').count(),2);
  await page.locator('[data-add="square-ui"]').click();
  assert.equal(await page.locator('#cropWarning').isVisible(),true);
  await page.locator('#assemblyName').fill('UI assembled sequence');
  await page.locator('#assemblyName').blur();
  await page.locator('#playSequence').click();
  await page.waitForFunction(()=>document.querySelector('#preview').currentTime>0);
  await page.locator('#stopPreview').click();
  await page.locator('#addFolder').click();
  const output=path.join(evidence,'exports-ui-'+Date.now());
  await page.locator('#folderPath').fill(output);
  await page.locator('#useFolder').click();
  await page.waitForFunction(()=>!document.querySelector('#folderDialog').open);
  await page.locator('#defaultFolder').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.startsWith('Assembly default saved'));
  assert.deepEqual(await (await page.request.get(base+'/api/output-folders')).json(),generationFolders);
  await page.reload();
  await page.locator('.timeline-clip').first().waitFor();
  assert.equal(await page.locator('.timeline-clip').count(),3);
  assert.equal(await page.locator('#assemblyFolder').inputValue(),output);
  assert.equal(await page.locator('#canvas').inputValue(),'largest');
  await page.locator('#export').click();
  assert.equal(await page.locator('#cropDialog').evaluate(d=>d.open),true);
  assert.match(await page.locator('#cropDescription').textContent(),/square-ui/);
  await page.locator('#cancelCrop').click();
  assert.equal((await (await page.request.get(base+'/api/assembly/exports')).json()).jobs.length,initialExportCount);
  await page.screenshot({path:path.join(evidence,'assembly-desktop.png'),fullPage:true});
  await page.locator('#export').click();
  const [submittedResponse]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/assembly/exports')&&r.request().method()==='POST'),page.locator('#confirmCrop').click()]);
  const submitted=await submittedResponse.json();
  await page.locator(`[data-export="${submitted.id}"] [data-action="play"]`).waitFor({timeout:30000});
  const state=await (await page.request.get(base+'/api/assembly/exports')).json();
  const exported=state.jobs[0];
  assert.equal(exported.status,'completed');
  assert.equal(exported.width,192);assert.equal(exported.height,128);
  assert.equal(exported.duration,1.25);
  assert.equal(exported.crop_confirmed,true);
  assert.deepEqual(exported.clips.map(c=>c.job_id),['blue-ui','red-ui','square-ui']);
  await page.locator('.export-card [data-action="play"]').first().click();
  await page.waitForFunction(()=>document.querySelector('#preview').readyState>=2);
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Download MP4'}).first().click()]);
  assert.ok((await download.path()));
  assert.match(download.suggestedFilename(),/UI-assembled-sequence.*\.mp4/);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(evidence,'assembly-mobile.png'),fullPage:true});
  await page.locator('.export-card [data-action="reuse"]').first().click();
  assert.equal(await page.locator('.timeline-clip').count(),3);
  await page.locator('.export-card [data-action="delete"]').first().click();
  await page.locator('#cancelDelete').click();
  assert.equal((await (await page.request.get(base+'/api/assembly/exports')).json()).jobs[0].status,'completed');
  assert.deepEqual(errors,[]);
  console.log('H3_ASSEMBLY_UI_PASSED: drag/drop, order, trims, undo, preview, persistence, separate folders, crop consent, export/download, reuse, mobile');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
