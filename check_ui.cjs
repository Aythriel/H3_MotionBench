const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('path');
const fs = require('fs');
const assert = require('assert/strict');

(async () => {
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.env.H3_DASHBOARD_URL || 'http://127.0.0.1:8788';
  const evidence = path.resolve(__dirname,'.artifacts/ui');
  fs.mkdirSync(evidence,{recursive:true});
  try {
    await page.goto(base);
    await page.waitForFunction(() => !document.querySelector('#generate').disabled);
    await page.locator('#pipelinePreset').selectOption('fl2va');
    assert.equal(await page.locator('#mode').inputValue(),'first');
    const initialRefs = await (await page.request.get(base+'/api/references')).json();
    assert.equal(await page.locator('#first').inputValue(),initialRefs[0]?.id || '');
    await page.locator('#mode').selectOption('both');
    await page.locator('#mode').selectOption('both');
    await page.locator('#copyFirst').click();
    assert.equal(await page.locator('#first').inputValue(),await page.locator('#last').inputValue());
    const firstReference = await page.locator('#first').inputValue();
    await page.locator('#clearLast').click();
    assert.equal(await page.locator('#last').inputValue(),'');
    assert.equal(await page.locator('#mode').inputValue(),'first');
    assert.equal(await page.locator('#first').inputValue(),firstReference);
    await page.locator('#mode').selectOption('both');
    await page.locator('#copyFirst').click();
    await page.locator('#last').selectOption('');
    assert.equal(await page.locator('#mode').inputValue(),'first');
    await page.reload();
    await page.waitForFunction(() => !document.querySelector('#generate').disabled);
    assert.equal(await page.locator('#last').inputValue(),'');
    assert.equal(await page.locator('#mode').inputValue(),'first');
    await page.locator('#quality').selectOption('square');
    assert.equal(await page.locator('#width').inputValue(),'512');
    await page.locator('#seconds').fill('5');
    assert.match(await page.locator('#timing').textContent(), /124 frames/);
    await page.locator('details').first().locator('summary').click();
    assert.equal(await page.locator('#advanced .info-button').count(),16);
    await page.locator('#help-model').hover();
    assert.equal(await page.locator('#settingTooltip').isVisible(),true);
    assert.match(await page.locator('#settingTooltip').textContent(),/main denoising model/);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#settingTooltip').isVisible(),false);
    await page.locator('#help-tiled').focus();
    assert.equal(await page.locator('#settingTooltip').isVisible(),true);
    assert.match(await page.locator('#settingTooltip').textContent(),/overlapping spatial/);
    await page.keyboard.press('Escape');
    assert.match(await page.locator('#budgetLive').textContent(),/used.*total/);
    assert.equal(await page.locator('.budget-component').count(),5);
    assert.doesNotMatch(await page.locator('#budgetComponents').textContent(),/Unknown size/);
    await page.locator('#encoder_device').selectOption('cpu');
    assert.match(await page.locator('[data-component="encoder"]').textContent(),/CPU \/ system RAM/);
    assert.equal(await page.locator('[data-component="encoder"] .budget-track span').evaluate(el=>el.style.width),'0%');
    await page.locator('#encoder_device').selectOption('default');
    await page.locator('#turbo').click();
    assert.equal(await page.locator('#steps').inputValue(),'8');
    assert.match(await page.locator('#lora').inputValue(),/turbo/);
    await page.locator('#base').click();
    assert.equal(await page.locator('#steps').inputValue(),'20');
    assert.equal(await page.locator('#lora').inputValue(),'');
    const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#savePreset').click()]);
    assert.equal(download.suggestedFilename(),'h3-settings.json');
    await page.locator('#budgetTitle').scrollIntoViewIfNeeded();
    await page.locator('#help-evict_after').hover();
    await page.screenshot({path:path.join(evidence,'dashboard-advanced.png'),fullPage:true});
    await page.keyboard.press('Escape');
    await page.locator('details').first().locator('summary').click();
    await page.locator('#mode').selectOption('first');
    await page.locator('#quality').selectOption('draft');
    assert.equal(await page.locator('#recipe').count(),0);
    await page.screenshot({path:path.join(evidence,'dashboard-desktop.png'),fullPage:true});
    await page.reload();
    await page.waitForFunction(() => !document.querySelector('#generate').disabled);
    assert.equal(await page.locator('#width').inputValue(),'608');
    const state = await (await page.request.get(base+'/api/status')).json();
    const complete = state.jobs.find(job => job.outputs.length);
    if (complete) {
      await page.locator(`[data-action="play"][data-id="${complete.id}"]`).click();
      await page.waitForFunction(() => document.querySelector('video').readyState >= 1);
      const media = await page.locator('video').evaluate(video => ({width:video.videoWidth,height:video.videoHeight,duration:video.duration}));
      assert.ok(media.width > 0 && media.duration > 0);
      await page.locator(`[data-action="delete"][data-id="${complete.id}"]`).click();
      assert.equal(await page.locator('#deleteDialog').evaluate(dialog => dialog.open),true);
      assert.match(await page.locator('#deleteDescription').textContent(),/settings remain in history/);
      assert.doesNotMatch(await page.locator('#deleteDescription').textContent(),/undefined|null/);
      await page.locator('#cancelDelete').click();
      assert.equal(await page.locator('#deleteDialog').evaluate(dialog => dialog.open),false);
      await page.locator('#nextFrame').click();
      await page.locator('#loopPlayback').check();
      assert.equal(await page.locator('video').evaluate(video => video.loop),true);
      const partial = await page.request.get(base+`/api/jobs/${complete.id}/video`,{headers:{Range:'bytes=0-99'}});
      assert.equal(partial.status(),206);
      const record = await (await page.request.get(base+`/api/jobs/${complete.id}/record`)).json();
      assert.ok(record.workflow.mux.inputs.audio);
      console.log('Verified video playback, frame step, loop, range download, and provenance');
      const promptBefore = await page.locator('#prompt').inputValue();
      const [frameDownload] = await Promise.all([
        page.waitForEvent('download', {timeout:120000}),
        page.locator('#saveLastFrame').click()
      ]);
      assert.equal(frameDownload.suggestedFilename(),`${complete.id}-last-frame.png`);
      const png = fs.readFileSync(await frameDownload.path());
      assert.equal(png.subarray(1,4).toString(),'PNG');
      assert.equal(png.readUInt32BE(16),media.width);
      assert.equal(png.readUInt32BE(20),media.height);
      await page.locator('#mode').selectOption('both');
      await page.locator('#mode').selectOption('both');
    await page.locator('#copyFirst').click();
      await page.locator('#useLastFrame').click();
      await page.waitForFunction(() => document.querySelector('#notice').textContent.startsWith('Last frame selected'));
      const continuationRef = await page.locator('#first').inputValue();
      assert.ok(continuationRef);
      assert.equal(await page.locator('#mode').inputValue(),'first');
      assert.equal(await page.locator('#last').inputValue(),'');
      assert.equal(await page.locator('#width').inputValue(),String(media.width));
      assert.equal(await page.locator('#height').inputValue(),String(media.height));
      assert.equal(await page.locator('#prompt').inputValue(),promptBefore);
      await page.reload();
      await page.waitForFunction(() => !document.querySelector('#generate').disabled);
      assert.equal(await page.locator('#first').inputValue(),continuationRef);
      assert.equal(await page.locator('#mode').inputValue(),'first');
      const shelf = await (await page.request.get(base+'/api/references')).json();
      assert.equal(shelf.find(ref => ref.id === continuationRef).source.job_id,complete.id);
      console.log('Verified final-frame PNG download, continuation selection and persistence without queuing a render');

    }
    const legacy = state.jobs.find(job => job.outputs.length && !job.config.output_folder);
    if (legacy) {
      await page.locator(`[data-action="delete"][data-id="${legacy.id}"]`).click();
      const description = await page.locator('#deleteDescription').textContent();
      assert.ok(description.includes(legacy.config.name));
      assert.match(description,/ComfyUI/);
      assert.doesNotMatch(description,/undefined|null/);
      await page.locator('#cancelDelete').click();
      console.log('Verified legacy take deletion confirmation without deleting user media');
    }
    await page.setViewportSize({width:390,height:844});
    await page.locator('#advanced summary').click();
    await page.locator('#help-model').click();
    const tipBox = await page.locator('#settingTooltip').boundingBox();
    assert.ok(tipBox && tipBox.x >= 0 && tipBox.x+tipBox.width <= 390);
    await page.screenshot({path:path.join(evidence,'dashboard-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),true,'No mobile overflow');
    assert.deepEqual(errors,[],'No page errors');
    console.log('H3_DASHBOARD_UI_PASSED');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
