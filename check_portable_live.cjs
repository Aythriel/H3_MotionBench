const {chromium} = require(process.env.PLAYWRIGHT_MODULE);
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8788/settings.html');
  await page.waitForFunction(()=>document.querySelector('#readiness').textContent.includes('3 model presets'));
  assert.equal(await page.locator('[data-model="b25"]').isChecked(),true);
  assert.match(await page.locator('body').innerText(),/recommended/i);
  assert.match(await page.locator('#planSummary').innerText(),/already available/);
  assert.equal(await page.locator('[data-path="comfy"]').getAttribute('aria-invalid'),'false');
  fs.mkdirSync('.artifacts/portable-live',{recursive:true});
  await page.screenshot({path:'.artifacts/portable-live/settings-desktop.png',fullPage:true});
  await page.goto('http://127.0.0.1:8788/');
  await page.waitForFunction(()=>!document.querySelector('#generate').disabled);
  assert.equal(await page.locator('#pipelinePreset').inputValue(),'hybrid_balanced');
  assert.ok(await page.locator('a[href="/settings.html"]:visible').count() >= 1);
  assert.equal(await page.locator('#inactiveTakes').evaluate(element=>element.open),false);
  assert.equal(await page.locator('#recipe').count(),0);
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:8788/settings.html');
  await page.waitForFunction(()=>document.querySelector('#readiness').textContent.includes('3 model presets'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('H3_PORTABLE_LIVE_UI_PASSED');
})().catch(error=>{console.error(error);process.exit(1)});
