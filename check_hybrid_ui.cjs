const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');

(async () => {
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const base = process.env.H3_DASHBOARD_URL || 'http://127.0.0.1:8792';
  const evidence = path.join(__dirname,'.artifacts/hybrid-ui');
  fs.mkdirSync(evidence,{recursive:true});
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  const ready=async()=>{await page.goto(base);await page.waitForFunction(()=>!document.querySelector('#generate').disabled);};
  try {
    await ready();
    assert.equal(await page.locator('#architecture').inputValue(),'hybrid');
    assert.equal(await page.locator('#mode').inputValue(),'first_reference');
    assert.equal(await page.locator('#firstBox').isVisible(),true);
    assert.equal(await page.locator('#lastBox').isVisible(),false);
    assert.equal(await page.locator('#identityBox').isVisible(),true);
    const refs=await (await page.request.get(base+'/api/references')).json();
    await page.locator('#identityPicker').selectOption(refs[1].id);
    await page.locator('#addIdentity').click();
    await page.locator('#identityPicker').selectOption(refs[2].id);
    await page.locator('#addIdentity').click();
    assert.equal(await page.locator('.identity-card').count(),2);
    assert.match(await page.locator('#firstTitle').textContent(), /Picture 1$/);
    assert.deepEqual(await page.locator('.identity-card strong').allTextContents(), ['Picture 2','Picture 3']);
    await page.locator('#mode').selectOption('both_reference');
    assert.match(await page.locator('#lastTitle').textContent(), /Picture 4$/);
    assert.equal(await page.locator('#lastBox').isVisible(),true);
    await page.locator('#copyFirst').click();
    await page.locator('#clearLast').click();
    assert.equal(await page.locator('#mode').inputValue(),'first_reference');
    assert.equal(await page.locator('#lastBox').isVisible(),false);
    await page.locator('#mode').selectOption('reference');
    assert.deepEqual(await page.locator('.identity-card strong').allTextContents(), ['Picture 1','Picture 2']);
    assert.equal(await page.locator('#firstBox').isVisible(),false);
    assert.equal(await page.locator('#identityBox').isVisible(),true);
    await page.locator('#mode').selectOption('text');
    assert.equal(await page.locator('#identityBox').isVisible(),false);
    assert.equal(await page.locator('#imagePreparation').isVisible(),false);
    await page.locator('#pipelinePreset').selectOption('hybrid_reference');
    assert.match(await page.locator('#model').inputValue(),/b20-49-int8.safetensors$/);
    assert.equal(await page.locator('#mode').inputValue(),'first_reference');
    await page.locator('#pipelinePreset').selectOption('fl2va');
    await page.waitForFunction(()=>document.querySelector('#architecture').value==='fl2va'); assert.equal(await page.locator('#architecture').inputValue(),'fl2va');
    assert.equal(await page.locator('#identityBox').isVisible(),false);
    assert.equal(await page.locator('#mode option[value="first_reference"]').count(),0);
    await page.locator('#pipelinePreset').selectOption('hybrid_balanced');
    assert.equal(await page.locator('.identity-card').count(),2);
    const before=await page.locator('#prompt').inputValue();
    await page.locator('[data-action="play"][data-id="synthetic-review"]').click();
    await page.locator('#useLastFrame').click();
    await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('Last frame selected'));
    assert.equal(await page.locator('#mode').inputValue(),'first_reference');
    assert.equal(await page.locator('.identity-card').count(),2);
    assert.equal(await page.locator('#prompt').inputValue(),before);
    await page.reload();await page.waitForFunction(()=>!document.querySelector('#generate').disabled);
    assert.equal(await page.locator('.identity-card').count(),2);
    const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#savePreset').click()]);
    const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(exported.architecture,'hybrid');assert.equal(exported.settings_version,3);
    assert.deepEqual(exported.identity_images,[refs[1].id,refs[2].id]);
    const old = {...exported,settings_version:2,prompt:'Start <Picture 3>; use face <Picture 1> and body <Picture 2>.'};
    await page.locator('#loadPreset').setInputFiles({name:'old-hybrid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(old))});
    await page.waitForFunction(()=>document.querySelector('#prompt').value.startsWith('Start <Picture 1>'));
    assert.equal(await page.locator('#prompt').inputValue(),'Start <Picture 1>; use face <Picture 2> and body <Picture 3>.');
    await page.reload();await page.waitForFunction(()=>!document.querySelector('#generate').disabled);
    assert.equal(await page.locator('#prompt').inputValue(),'Start <Picture 1>; use face <Picture 2> and body <Picture 3>.');
    await page.screenshot({path:path.join(evidence,'desktop.png'),fullPage:true});
    await page.locator('#advanced summary').click();
    assert.equal(await page.locator('#turbo').isDisabled(),true);
    assert.match(await page.locator('#budgetComponents').textContent(),/H3 generator/);
    await page.locator('#advanced summary').click();
    const legacy={...exported,model:'MiniMax-H3-fl2va-curve-Q4_0.gguf',mode:'first',prompt:'Legacy prompt to retain'};
    delete legacy.architecture;delete legacy.settings_version;delete legacy.identity_images;
    await page.locator('#loadPreset').setInputFiles({name:'legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(legacy))});
    await page.waitForFunction(()=>document.querySelector('#architecture').value==='fl2va'); assert.equal(await page.locator('#architecture').inputValue(),'fl2va');
    assert.equal(await page.locator('#mode').inputValue(),'first');
    await page.evaluate(value=>localStorage.setItem('h3-workbench-settings',JSON.stringify(value)),legacy);
    await page.reload();await page.waitForFunction(()=>!document.querySelector('#generate').disabled);
    assert.equal(await page.locator('#architecture').inputValue(),'hybrid');
    assert.equal(await page.locator('#mode').inputValue(),'first_reference');
    assert.equal(await page.locator('#prompt').inputValue(),'Legacy prompt to retain');
    assert.equal(await page.evaluate(()=>!!localStorage.getItem('h3-workbench-settings-pre-hybrid')),true);
    await page.locator('#identityPicker').selectOption(refs[1].id);await page.locator('#addIdentity').click();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(evidence,'mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.deepEqual(errors,[]);
    console.log('H3_HYBRID_UI_PASSED');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
