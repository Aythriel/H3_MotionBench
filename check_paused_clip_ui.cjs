const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('assert/strict');
const path=require('path');
(async()=>{
 const base=process.env.H3_ASSEMBLY_TEST_URL||'http://127.0.0.1:8791';
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(base+'/assemble.html');
  await page.locator('[data-add="red-ui"]').waitFor();
  assert.equal(await page.locator('#savePausedClip').isDisabled(),true);
  await page.locator('[data-add="red-ui"]').click();
  await page.waitForFunction(()=>!document.querySelector('#savePausedClip').disabled);
  await page.locator('#followingFrame').click();
  await page.waitForFunction(()=>document.querySelector('#pausedFrameInfo').textContent.includes('source frame 2.'));
  await page.locator('#followingFrame').click();
  await page.waitForFunction(()=>document.querySelector('#pausedFrameInfo').textContent.includes('source frame 3.'));
  await page.locator('#previousFrame').click();
  await page.waitForFunction(()=>document.querySelector('#pausedFrameInfo').textContent.includes('source frame 2.'));
  await page.locator('#preview').evaluate(v=>{v.pause();v.currentTime=5/24+0.00001;});
  await page.waitForFunction(()=>document.querySelector('#pausedFrameInfo').textContent.includes('source frame 6.')&&!document.querySelector('#savePausedClip').disabled);
  await page.locator('#savePausedClip').click();
  assert.equal(await page.locator('#nameDialog').evaluate(d=>d.open),true);
  assert.match(await page.locator('#nameDescription').textContent(),/frames 1–6/);
  const clipName='Good frames '+Date.now();
  await page.locator('#clipName').fill(clipName);
  const [response]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/assembly/clip')&&r.request().method()==='POST'),page.locator('#confirmName').click()]);
  const exportJob=await response.json();assert.equal(response.status(),202);
  assert.equal(exportJob.frame_end,5);
  await page.locator(`[data-add="${exportJob.id}"]`).waitFor({timeout:30000});
  const job=await (await page.request.get(base+`/api/jobs/${exportJob.id}/record`)).json();
  assert.equal(job.config.frames,6);assert.equal(job.kind,'clip');assert.equal(job.config.name,clipName);
  await page.locator(`[data-add="${exportJob.id}"]`).click();
  assert.equal(await page.locator('#savePausedClip').isDisabled(),true);
  await page.locator('#clearTimeline').click();
  await page.locator(`[data-add="${exportJob.id}"]`).click();
  await page.waitForFunction(id=>{const v=document.querySelector('#preview');return v.src.includes(id)&&v.readyState>=2;},exportJob.id);
  assert.equal(await page.locator('#preview').evaluate(v=>v.error),null);
  await page.locator('[data-rename="red-ui"]').click();
  await page.locator('#clipName').fill('Renamed original UI');
  await page.locator('#confirmName').click();
  await page.waitForFunction(()=>!document.querySelector('#nameDialog').open);
  assert.match(await page.locator('[data-source="red-ui"]').textContent(),/Renamed original UI/);
  await page.goto(base+'/');
  await page.locator(`[data-action="play"][data-id="${exportJob.id}"]`).click();
  await page.waitForFunction(()=>document.querySelector('#video').readyState>=2);
  assert.match(await page.locator('#selectedInfo').textContent(),/Saved clip/);
  await page.locator(`[data-action="rename"][data-id="${exportJob.id}"]`).click();
  await page.locator('#renameName').fill('Useful endpoint copy');
  await page.locator('#confirmRename').click();
  await page.waitForFunction(()=>!document.querySelector('#renameDialog').open);
  assert.match(await page.locator('#selectedInfo').textContent(),/Useful endpoint copy/);
  await page.locator('#useLastFrame').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.startsWith('Last frame selected'));
  assert.ok(await page.locator('#first').inputValue());
  assert.equal(await page.locator('#mode').inputValue(),'first');
  const refs=await (await page.request.get(base+'/api/references')).json();
  const first=await page.locator('#first').inputValue();
  assert.equal(refs.find(r=>r.id===first).source.job_id,exportJob.id);
  await page.goto(base+'/assemble.html');
  await page.locator(`[data-source="${exportJob.id}"]`).waitFor();
  assert.match(await page.locator(`[data-source="${exportJob.id}"]`).textContent(),/Useful endpoint copy/);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(__dirname,'.artifacts/assembly-review/paused-clip-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  await page.request.post(base+'/api/jobs/red-ui/rename',{data:{name:'red-ui'}});
  console.log('H3_PAUSED_CLIP_UI_PASSED: frame stepping, inclusive capture, playable saved copy, inventory names, persistence and last-frame continuation');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
